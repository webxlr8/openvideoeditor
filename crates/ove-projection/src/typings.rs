//! `timeline.d.ts`, generated from the same field registry the parser validates against (design D8), so editor
//! completions match what `check` accepts.

use ove_core::schema::{self, Field, Kind};

use crate::print::{attr_for, tag_for};

fn ts(k: &Kind) -> String {
    match k {
        Kind::Str => "string".into(),
        Kind::Bool => "boolean".into(),
        Kind::Num { .. } | Kind::Int { .. } => "number".into(),
        Kind::Time | Kind::SignedTime => "Seconds".into(),
        Kind::Any => "unknown".into(),
        Kind::Enum(v) => v.iter().map(|s| format!("\"{s}\"")).collect::<Vec<_>>().join(" | "),
        Kind::Arr(e) => match e {
            Kind::Enum(_) => format!("({})[]", ts(e)),
            _ => format!("{}[]", ts(e)),
        },
        Kind::Obj { fields, .. } => {
            // Unknown keys are accepted by `check` (closed objects warn), so the typings accept them too.
            let mut parts: Vec<String> = fields.iter().map(|f| format!("{}?: {}", f.name, ts(&f.kind))).collect();
            parts.push("[key: string]: unknown".into());
            format!("{{ {} }}", parts.join("; "))
        }
    }
}

fn prop(out: &mut String, f: &Field, name: &str) {
    if !f.doc.is_empty() {
        out.push_str(&format!("  /** {} */\n", f.doc));
    }
    out.push_str(&format!("  {name}?: {};\n", ts(&f.kind)));
}

fn pascal(s: &str) -> String {
    let mut c = s.chars();
    c.next().map(|f| f.to_ascii_uppercase().to_string() + c.as_str()).unwrap_or_default()
}

/// The typings text.
pub fn typings() -> String {
    let mut s = String::from(
        "// Typings for timeline.tsx (projection format 1). Generated by the app from its document schema; do not edit.\n\
// Values must be literals. Unknown attributes are kept as they are (hence the index signatures).\n\n\
/** Seconds, stored at microsecond precision. */\ntype Seconds = number;\n\n",
    );
    s.push_str(&format!(
        "type Aspect = {};\ntype TrackKind = {};\n\n",
        ts(&Kind::Enum(schema::ASPECT_RATIOS)),
        ts(&Kind::Enum(schema::TRACK_TYPES))
    ));
    s.push_str("interface TimelineProps {\n  aspect?: Aspect;\n  children?: unknown;\n}\n\n");
    s.push_str("interface TrackProps {\n  /** Track id; omit for a new track. */\n  id?: string;\n  name?: string;\n  kind: TrackKind;\n");
    for f in schema::TRACK_FIELDS {
        prop(&mut s, f, f.name);
    }
    s.push_str("  children?: unknown;\n  [attribute: string]: unknown;\n}\n\n");
    s.push_str(
        "interface ItemBase {\n  /** Item id; omit for a new item. */\n  id?: string;\n  /** Timeline start. */\n  start: Seconds;\n  /** Timeline end (after start). */\n  end: Seconds;\n  /** Media name from the header, media id, or a file path (absolute, ./, ../, ~/). */\n  src?: string;\n  [attribute: string]: unknown;\n}\n\n",
    );
    for t in schema::ITEM_TYPES {
        s.push_str(&format!("interface {}Props extends ItemBase {{\n", pascal(tag_for(t))));
        for f in schema::item_fields(t) {
            if f.name == "mediaItemId" {
                continue;
            }
            prop(&mut s, f, attr_for(f.name));
        }
        s.push_str("}\n\n");
    }
    s.push_str("declare global {\n  namespace JSX {\n    interface Element {}\n    interface IntrinsicElements {\n");
    s.push_str("      timeline: TimelineProps;\n      track: TrackProps;\n");
    for t in schema::ITEM_TYPES {
        s.push_str(&format!("      {}: {}Props;\n", tag_for(t), pascal(tag_for(t))));
    }
    s.push_str("    }\n  }\n}\n\nexport {};\n");
    s
}
