//! Writes the nine preset looks as `.cube` files (17³) into `assets/luts/`, so they can be used in other tools.
//! The renderer itself evaluates the same looks procedurally (see `ove_render::color::preset_fn`).
//!
//!   cargo run -p ove-render --example gen_luts
#![allow(
    clippy::unwrap_used,
    clippy::expect_used,
    clippy::panic,
    clippy::unreachable,
    reason = "developer example, not shipped: failing loudly on a broken setup is the point"
)]

use std::path::PathBuf;

use ove_render::color::{LUT_PRESETS, Lut, preset_fn};

fn main() {
    let dir = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../assets/luts");
    std::fs::create_dir_all(&dir).expect("create assets/luts");
    for (id, label) in LUT_PRESETS {
        let f = preset_fn(id).expect("preset");
        let lut = Lut::from_fn(17, |c| f(c).map(|v| v.clamp(0.0, 1.0)));
        let header = format!(
            "{label} look for OpenVideoEditor.\nGenerated by crates/ove-render/examples/gen_luts.rs; dedicated to the \
             public domain under CC0-1.0 (see LICENSE)."
        );
        let path = dir.join(format!("{id}.cube"));
        std::fs::write(&path, lut.to_cube(label, &header)).expect("write lut");
        println!("wrote {}", path.display());
    }
}
